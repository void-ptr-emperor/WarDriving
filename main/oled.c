void memset_oled_buffer(void)
{

    memset(oled_buffer , 0 , sizeof(oled_buffer));

}

void write_pixel_in_oled_buffer(uint8_t x, uint8_t y,  bool position)
{

    if (x > 127 || y > 63 )
        return;

    uint8_t page = y / 8;

    uint8_t bit = y % 8;

    uint16_t cursor = (page * 128) + x;

    if (cursor < 1024){
        if (position){
            oled_buffer[cursor] = oled_buffer[cursor] | (1 <<  bit);
        }else{
            oled_buffer[cursor] = oled_buffer[cursor] & ~(1 << bit);

        }
    }

}

void write_text_pixel(const char *text , uint8_t x_start , uint8_t y_start)
{

    for(int i = 0; text[i] != '\0'; i++) {
        
        uint8_t _char = text[i]; 
        
        if (_char < 32 || _char > 126) 
            _char = 32; 
            
        uint8_t index_in_ascii = _char - 32;

        for(uint8_t j = 0; j < 5; j++) {
            uint8_t font_byte = ascii[index_in_ascii][j]; 
            
            for(uint8_t bit = 0; bit < 8; bit++) {
                if (font_byte & (1 << bit)) {
                    write_pixel_in_oled_buffer(x_start, y_start + bit, true);
                }
            }
            x_start++; 
        }
        x_start++; 
    }

}

void write_h_line_in_oled_buffer(uint8_t x_start , uint8_t x_end , uint8_t y )
{

    for(uint8_t current_x = x_start; current_x <= x_end ; current_x++)
        write_pixel_in_oled_buffer(current_x, y,true);

}

void write_v_line_in_oled_buffer(uint8_t x , uint8_t y_start , uint8_t y_end )
{

    for(uint8_t current_y = y_start ; current_y <= y_end ; current_y++)
        write_pixel_in_oled_buffer(x , current_y  , true );

}

void write_invert_pixel(uint8_t x, uint8_t y)
{

    if (x > 127 || y > 63 )
        return;

    uint8_t page = y / 8;

    uint8_t bit = y % 8;

    uint16_t cursor = (page * 128) + x;

    if (cursor < 1024)      
            oled_buffer[cursor] ^= (1 << bit);
        
    
}

void write_invert_area(uint8_t x_start, uint8_t x_end, uint8_t y_start, uint8_t y_end)
{
    if (x_end > 127) x_end = 127;
    if (y_end > 63)  y_end = 63;

    for (uint8_t x = x_start; x <= x_end; x++) {
        for (uint8_t y = y_start; y <= y_end; y++) {
            
            write_invert_pixel(x, y);
            
        }


    }

}

void write_invert_square(uint8_t square_index)
{
    uint8_t x_start = 1;
    uint8_t x_end = 126;
    uint8_t y_start = 17 + (square_index * 12);
    uint8_t y_end = 27 + (square_index * 12);

    if (y_end >= 63) {
        y_end = 62;
    }

    write_invert_area(x_start, x_end, y_start, y_end);
}

void write_frames(void)
{

    write_h_line_in_oled_buffer(0, 127, 0);
    write_h_line_in_oled_buffer(0, 127, 15);
    write_v_line_in_oled_buffer(0, 0, 15 );
    write_v_line_in_oled_buffer(127, 0, 15 );


    write_h_line_in_oled_buffer(0, 127, 16);
    write_h_line_in_oled_buffer(0, 127, 63);
    write_v_line_in_oled_buffer(0, 16, 63 );
    write_v_line_in_oled_buffer(127, 16, 63);

}

void oled_set_default_settings(void)
{

    gpio_set_direction(SPI_OLED_RES_PIN , GPIO_MODE_OUTPUT);
    gpio_set_direction(SPI_OLED_DC_PIN , GPIO_MODE_OUTPUT);

    gpio_set_level(SPI_OLED_RES_PIN, 0);            
    vTaskDelay(100 / portTICK_PERIOD_MS);          
    gpio_set_level(SPI_OLED_RES_PIN, 1);            
    vTaskDelay(100 / portTICK_PERIOD_MS);

    spi_transaction_oled(oled_cmds , 0 ,sizeof(oled_cmds));

}

void oled_send_cmd(uint8_t cmd)
{

   spi_transaction_oled(&cmd , 0 , 1);

}

void oled_begin(void)
{

    spi_transaction_oled(oled_buffer , 1 , sizeof(oled_buffer));
}

